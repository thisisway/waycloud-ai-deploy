$call = static function (array $e, array $body, ?callable $tamper = null, string $method = 'POST'): array {
    $raw = json_encode($body);
    $s = Hmac::sign(SECRET, $raw, $e['clock']->t, bin2hex(random_bytes(8)));
    $h = ['x-waycloud-timestamp' => (string) $s['ts'], 'x-waycloud-nonce' => $s['nonce'], 'x-waycloud-signature' => $s['signature']];
    if ($tamper) {
        [$h, $raw] = $tamper($h, $raw);
    }
    return $e['api']->handle($method, $h, $raw);
};
test('rejects anything that is not a valid signed POST, without saying why', function () use ($call) {
    $e = make();
    eq(405, $call($e, ['action' => 'ping'], null, 'GET')[0]);
    eq([401, ['error' => 'unauthorized']], $call($e, ['action' => 'ping'], fn ($h, $r) => [[], $r]), 'no headers');
    eq([401, ['error' => 'unauthorized']], $call($e, ['action' => 'ping'], fn ($h, $r) => [$h, $r . ' ']), 'tampered body');
    eq([401, ['error' => 'unauthorized']], $call($e, ['action' => 'ping'], fn ($h, $r) => [['x-waycloud-timestamp' => (string) ($e['clock']->t - 400)] + $h, $r]), 'stale timestamp is not enough');
    $unconfigured = make(false);
    eq(401, $unconfigured['api']->handle('POST', [], '{"action":"ping"}')[0], 'no secret configured');
});
test('a rejected request is still a 401 when the log itself fails (tables not created yet)', function () {
    $e = make();
    $failing = new class extends MemoryStore {
        public function logEvent(string $type, ?string $ref, array $data, int $now): void
        {
            throw new RuntimeException('table mod_waycloud_events does not exist');
        }
    };
    $api = new Api($failing, new Settings(['hmac_secret' => '']), $e['checkout'], $e['whmcs'], static fn (): int => 1_700_000_000);
    eq([401, ['error' => 'unauthorized']], $api->handle('POST', [], '{"action":"ping"}'));
});
