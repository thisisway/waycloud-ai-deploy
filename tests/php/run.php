    $e['posted']->status = 0;
    $e['checkout']->submit(newToken($e), $valid);
    eq(1, $e['store']->pendingOutbox());
    $e['store']->markEventFailed(1, 20, 0);
    $e['notifier']->flush();
    eq(1_700_000_000 + 3600, $e['store']->outbox[1]['next_attempt_at']);
});

