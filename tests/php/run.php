/** @return array{store:MemoryStore, whmcs:FakeWhmcs, checkout:Checkout, notifier:McpNotifier, api:Api, clock:object, posted:object} */
function make(bool $configured = true): array
{
    $store = new MemoryStore();
    $whmcs = new FakeWhmcs();
    $clock = new class { public int $t = 1_700_000_000; };
    $posted = new class { public array $calls = []; public int $status = 200; };
    $settings = new Settings($configured ? ['mcp_url' => 'https://mcp.test/', 'hmac_secret' => SECRET] : []);
    $now = static fn (): int => $clock->t;
    $notifier = new McpNotifier($store, $settings, static function (string $url, array $headers, string $body) use ($posted): int {
        $posted->calls[] = compact('url', 'headers', 'body');
        return $posted->status;
    }, $now);
    $rng = new class { public int $i = 0; };
    $rand = static fn (int $n): string => substr(hash('sha256', 'seed' . $rng->i++, true) . hash('sha256', 'more' . $rng->i, true), 0, $n);
    $checkout = new Checkout($store, $whmcs, $settings, $notifier, $now, $rand);
    $api = new Api($store, $settings, $checkout, $whmcs, $now);
    return compact('store', 'whmcs', 'checkout', 'notifier', 'api', 'clock', 'posted');
}

/** Creates a checkout and returns its token. */
function newToken(array $env, int $pid = 173, string $cycle = 'monthly'): string
{
    $r = $env['checkout']->createFromMcp(['session_id' => SESSION, 'pid' => $pid, 'cycle' => $cycle]);
    preg_match('/t=([A-Za-z0-9_-]+)$/', $r['checkout_url'], $m);
    return $m[1];
}

