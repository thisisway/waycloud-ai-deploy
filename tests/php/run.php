test('verify: 5 minute window and secret guard', function () {
    $store = new MemoryStore();
    $old = Hmac::sign(SECRET, 'b', 1000, 'nonce-aaaaaa');
    eq('expired', Hmac::verify($store, SECRET, 1000, 'nonce-aaaaaa', $old['signature'], 'b', 1301));
    $fresh = Hmac::sign(SECRET, 'b', 1000, 'nonce-bbbbbb');
    eq('ok', Hmac::verify($store, SECRET, 1000, 'nonce-bbbbbb', $fresh['signature'], 'b', 1299));
