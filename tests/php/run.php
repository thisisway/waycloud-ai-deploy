test('ping, plans, create_checkout, unknown action and invalid json', function () use ($call) {
    $e = make();
    eq([200, ['ok' => true]], $call($e, ['action' => 'ping']));
    [$s, $plans] = $call($e, ['action' => 'plans']);
    eq(200, $s);
    eq([['static', 173], ['php', 174]], array_map(fn ($p) => [$p['type'], $p['pid']], $plans['plans']));
    [$s, $r] = $call($e, ['action' => 'create_checkout', 'session_id' => SESSION, 'pid' => 173, 'cycle' => 'annually']);
    eq(200, $s);
    yes(str_starts_with($r['checkout_url'], 'https://app.test/index.php?m=waycloud_ai&t='), 'url');
    eq([422, ['error' => 'invalid_plan']], $call($e, ['action' => 'create_checkout', 'session_id' => SESSION, 'pid' => 1, 'cycle' => 'monthly']));
    eq([400, ['error' => 'unknown_action']], $call($e, ['action' => 'drop_tables']));
    $raw = 'not json';
    $sig = Hmac::sign(SECRET, $raw, $e['clock']->t, 'nonce-json-1');
    eq(400, $e['api']->handle('POST', ['x-waycloud-timestamp' => (string) $sig['ts'], 'x-waycloud-nonce' => $sig['nonce'], 'x-waycloud-signature' => $sig['signature']], $raw)[0]);
});

